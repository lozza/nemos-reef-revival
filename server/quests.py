"""Quests: the story content (story.json) and the per-player quest state.

Quest progression is server-driven (see QUESTS.md): the client only runs quests the server gives it,
either in the startgame "quests" list (state 9 = running, 8 = offered) or pushed as a type-2 message.
The client detects task progress itself and reports each step with questTaskSetState; when every task
is finished the server credits the reward, records the quest as finished and pushes the next ones.

story.json (generated by tools/build_story.py) holds the content: quests with their tasks, rewards, the level
they open at and the quests they wait for; dialogs, hints, fish-attraction patterns and the items the quests use.
All texts are keys of the game's own text table (served from the APK); story.json "texts" adds any extra ones.
"""
import calendar
import copy
import datetime
import glob
import hashlib
import json
import os
import time

import worlddef
import economy

STORY = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'story.json')
RUNNING, OFFERED = 9, 8
# task conditions whose parameter 2 is a prototype id (QCondition*::loadParameters)
PROTOTYPE_TASKS = ('CID_CREATED', 'CID_CREATED_EXISTS', 'CID_BUILT', 'CID_BUILT_EXISTS', 'CID_GROWN', 'CID_FERTILIZE',
                   'CID_HARVESTED', 'CID_HARVESTED_AMOUNT', 'CID_MOVED_ON_PATCH', 'CID_FISH_REWARD_COLLECTED',
                   'CID_FISH_REWARD_COLLECTED_AMOUNT')
QUEST_OPEN, QUEST_FINISH = 2, 6  # message types


def reward(r):
    r = r or {}
    return {k: int(r.get(k, 0)) for k in ('xp', 'virtualMoney', 'energy', 'hardMoney', 'lowTool', 'highTool')}


def cost(c):
    c = c or {}
    return {k: int(c.get(k, 0)) for k in ('energy', 'virtualMoney', 'hardMoney', 'lowTool', 'highTool')}


# Treasure ("Epic") fish and the months of their 2014 chest challenges (wiki: April-May, June, July, August)
TREASURE_FISH = {'fish_treasure_lyretail': (4, 5), 'fish_treasure_panther': (6, 6),
                 'fish_treasure_trigger': (7, 7), 'fish_treasure_popeye': (8, 8)}
# Chests opened during its month after which the treasure fish surely comes (before that, 1 in 5 chests)
TREASURE_CHESTS = 6

# Time events that run now whatever the date (nemo_server.py --event, for testing)
FORCED_EVENTS = {}  # quest id -> start (ms)

# Decorations sold only during their holiday event
SEASONAL_ITEMS = {'deco_halloween_rock_orange': 'halloween', 'deco_halloween_skull': 'halloween'}

# Fish whose prototype "name" is a placeholder: the game's own text keys (or plain names) for them
NAME_FIXES = {
    'fish_ambient_0': 'STF_AMBIENT_FISH_0',
    'fish_ambient_1': 'STF_AMBIENT_FISH_1',
    'fish_ambient_coralfish': 'STF_AMBIENT_CORALFISH',
    'fish_ambient_firefish': 'STF_AMBIENT_FIREFISH',
    'fish_rare_lion': 'Lionfish',
    'fish_rare_vampire': 'STR_NAME_CRAB_VAMPIRE',
}


class Story:
    def __init__(self, path=STORY, kids=False, economy_mode=None):
        """kids: build the Kids edition's worldDef (players under the game's age limit): the Kids missions' texts,
        hints and easier combinations. Quest progress works the same for both."""
        self.kids = kids
        with open(path, encoding='utf-8') as f:
            self.data = json.load(f)
        self.economy_mode = economy.mode(economy_mode)
        economy.configure_story(self.data, self.economy_mode)
        self.quests = {q['id']: q for q in self.data['quests']}
        self.renamed = self.data.get('renamed', {})

    # ------------------------------------------------------------ worldDef / texts
    def texts(self):
        """Texts the APK's text table does not have: item names made up for prototypes without one, and
        story.json "texts"."""
        t = dict(getattr(self, 'names', {}))
        t.update(self.data.get('texts', {}))
        return t

    # ------------------------------------------------------------ time events
    WEEK = 7 * 24 * 3600 * 1000
    EPOCH = calendar.timegm((2014, 1, 3, 0, 0, 0)) * 1000  # a Friday: weekend events run Friday to Monday
    SEASONS = {'christmas': ((12, 8), (12, 31)), 'halloween': ((10, 18), (11, 3)),
               'valentine': ((2, 7), (2, 17)), 'easter': ((3, 28), (4, 14))}

    @staticmethod
    def month_window(m1, m2, now):
        """The current or next window from the 1st of month m1 to the end of month m2 (ms)."""
        year = datetime.datetime.utcfromtimestamp(now / 1000).year
        for y in (year, year + 1):
            start = calendar.timegm((y, m1, 1, 0, 0, 0)) * 1000
            end = calendar.timegm((y + (m2 == 12), m2 % 12 + 1, 1, 0, 0, 0)) * 1000 - 1000
            if end > now:
                return start, end
        return start, end

    def in_season(self, season, now=None):
        (m1, d1), (m2, d2) = self.SEASONS[season]
        today = datetime.datetime.utcfromtimestamp((now or time.time() * 1000) / 1000)
        return (m1, d1) <= (today.month, today.day) <= (m2, d2)

    def event_windows(self, now):
        """{quest id: (start ms, end ms)}: each time event's current or next window. Seasonal events come on their
        dates every year; the others take turns, one each weekend. A chain (a, b, c) shares its first part's."""
        events = [q for q in self.data['quests'] if q.get('event')]
        roots = [q for q in events if not q['event'].get('after')]
        weekend = [q['id'] for q in roots if q['event']['season'] == 'weekend']
        out = {}
        for q in roots:
            season = q['event']['season']
            if season in self.SEASONS:
                (m1, d1), (m2, d2) = self.SEASONS[season]
                year = datetime.datetime.utcfromtimestamp(now / 1000).year
                for y in (year, year + 1):
                    start = calendar.timegm((y, m1, d1, 0, 0, 0)) * 1000
                    end = calendar.timegm((y, m2, d2, 23, 59, 59)) * 1000
                    if end > now:
                        break
            elif q['id'] in FORCED_EVENTS:  # --event: running now (testing)
                start = FORCED_EVENTS[q['id']]
                end = start + 3 * 24 * 3600 * 1000
            else:
                n, i = len(weekend), weekend.index(q['id'])
                k = (now - self.EPOCH) // self.WEEK
                while True:
                    start = self.EPOCH + k * self.WEEK
                    end = start + 3 * 24 * 3600 * 1000
                    if k % n == i and end > now:
                        break
                    k += 1
            out[q['id']] = (start, end)
        for q in events:  # chain parts
            root = q
            while root['event'].get('after'):
                root = self.quests[root['event']['after']]
            out[q['id']] = out[root['id']]
        return out

    def run_events(self, w, now, push=True):
        """Opens the time events running now (level 6 and up) and takes away the ones whose window is over."""
        windows = self.windows if getattr(self, 'windows', None) else self.event_windows(now)
        done = w.setdefault('eventsDone', {})
        keep = []
        for e in w['quests']:
            q = self.quests.get(e['prototypeId'], {})
            if q.get('event') and not (windows[q['id']][0] <= now < windows[q['id']][1]):
                continue  # the event is over
            keep.append(e)
        w['quests'] = keep
        if int(w['status'].get('level', 1)) < 6:
            return
        open_ids = {e['prototypeId'] for e in w['quests']}
        for q in self.data['quests']:
            if not q.get('event') or q['id'] in open_ids:
                continue
            start, end = windows[q['id']]
            if not start <= now < end or done.get(q['id']) == start:
                continue
            prev = q['event'].get('after')
            if prev and done.get(prev) != start:
                continue
            self.open(w, q['id'], push)

    def extend_worlddef(self, wd):
        wd['revivalEconomy'] = self.economy_mode
        if self.economy_mode == 'revival':
            wd['exchangePackagePrototypes'] = economy.packages(economy.MIN_LEVEL)
            # Remove the recurring premium-seed sales prompt; rare plants can
            # be earned through the ordinary seed route.
            wd['globalSettings']['lowVitality_minLevel'] = economy.MAX_LEVEL + 1
        self.windows = self.event_windows(int(time.time() * 1000))
        now = int(time.time() * 1000)  # rebuilt when an event window opens or closes (seasonal shop items)
        self.treasure = {fid: self.month_window(m1, m2, now) for fid, (m1, m2) in TREASURE_FISH.items()}
        self.events_until = min((end if start <= now else start
                                 for start, end in list(self.windows.values()) + list(self.treasure.values())), default=0)
        # Treasure fish (wiki "Epic fish"): EntityFish/ServerPrototype::getTreasureFishInterval reads the window
        # from "conditions" (CID_TIME_INTERVAL, 1 = start ms, 2 = end ms); during it the game reminds the player to
        # open chests for the fish (DialogFlowTreasure::checkPopUpOpenChestToGetFish).
        for p in wd.get('fishPrototypeList', []):
            if p.get('id') in self.treasure:
                start, end = self.treasure[p['id']]
                p['conditions'] = [{'conditionDefinitionId': 'CID_TIME_INTERVAL', 'parameterValueList': [
                    {'index': 1, 'value': start}, {'index': 2, 'value': end}]}]
        self.add_items(wd)
        self.levels(wd)
        self.name_keys(wd)
        # The client keeps a downloaded texts bundle per (id, language) and never asks again for an id it
        # already has (Action_GetTextBundle::canSkipNetAction), so the id must change whenever the texts do.
        h = hashlib.sha1(json.dumps(self.texts(), sort_keys=True).encode('utf-8'))
        for f in sorted(glob.glob(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'texts_*.json'))):
            with open(f, 'rb') as fh:
                h.update(fh.read())
        wd['localizedTextsBundleId'] = 2 + int(h.hexdigest()[:7], 16)
        wd['questPrototypeList'] = [self.quest_prototype(q) for q in self.data['quests']]
        wd['dialogPrototypeList'] = [
            {'id': d['id'], 'conditionList': [
                {'position': l['side'], 'actorId': l['actor'], 'toActorId': l.get('listener', ''), 'textId': l['key']}
                for l in d['lines']]}
            for d in self.data.get('dialogs', [])]
        wd['hintPrototypeList'] = [{'id': h['id'], 'cost': cost(h.get('cost')), 'index': h.get('index', 0),
                                    'textId': h['key']} for h in self.data.get('hints', [])]
        wd['patternList'] = [dict({k: v for k, v in p.items() if k != 'kidsOnly'},
                                  centralHintCost=cost(p.get('centralHintCost')),
                                  sorroundingHintCost=cost(p.get('sorroundingHintCost')))
                             for p in self.data.get('patterns', []) if self.kids or not p.get('kidsOnly')]
        wd['conditionDefinitionList'] = []
        if self.data.get('vitalityPatchList'):  # the 2014 game's own list
            wd['vitalityPatchList'] = self.data['vitalityPatchList']
        self.check(wd)

    def add_items(self, wd):
        """Colour variants and the real shop values from story.json "items"."""
        colors = dict(worlddef.SQUIRT_ZONE_COLORS, **self.data.get('colors', {}))
        wd['colorVariantList'] = [{'id': c, 'color': {'alpha': 255, 'red': v[0], 'green': v[1], 'blue': v[2]}}
                                  for c, v in colors.items()]
        lists = [k for k in wd if k.endswith('PrototypeList') or k == 'patchList']
        by_id = {p['id']: (k, p) for k in lists if isinstance(wd[k], list) for p in wd[k] if isinstance(p, dict)}
        shop = {s['prototypeId']: s for s in wd['ingameShopItems']}
        has_variants = set()
        for pid, it in self.data.get('items', {}).items():
            base = it.get('base')
            if base:
                if base not in by_id:
                    raise ValueError('item %s: unknown base prototype %s' % (pid, base))
                lst, bp = by_id[base]
                p = copy.deepcopy(bp)
                p['id'] = pid
                p['graphicalId'] = base
                wd[lst].append(p)
                by_id[pid] = (lst, p)
                has_variants.add(base)
            elif pid in by_id:
                p = by_id[pid][1]
            else:
                raise ValueError('item %s: unknown prototype' % pid)
            if it.get('color'):
                p['colorVariantId'] = it['color']
            if it.get('name'):  # a key of the game's text table, or a plain name
                p['name'] = p['nameId'] = it['name']
            if it.get('price'):
                pc = it['price']
                p['cost'] = worlddef.cost(coins=pc.get('virtualMoney', 0), pearls=pc.get('hardMoney', 0))
                p['refundReward'] = worlddef.reward(coins=p['cost']['virtualMoney'] // 2)
            if 'feed' in it:
                p['growingCycleCost'] = worlddef.cost(algae=it['feed'])
            if 'step' in it:
                p['growingTime'] = worlddef.duration(it['step'])
            if 'produce' in it:
                pr = it['produce']
                p['producedReward'] = worlddef.reward(xp=pr.get('xp', 0), coins=pr.get('virtualMoney', 0),
                                                      algae=pr.get('energy', 0), pearls=pr.get('hardMoney', 0))
            if 'fishFeed' in it:  # rare fish: algae per feeding, then produce every "every" seconds
                p['producingCost'] = worlddef.cost(algae=it['fishFeed'])
            if 'results' in it:
                p['seedResults'] = list(it['results'])
            if 'every' in it:
                p['producingTime'] = worlddef.duration(it['every'])
            if 'hearts' in it:
                p['vitality'] = it['hearts']
            if 'build' in it:
                p['constructionTime'] = worlddef.duration(it['build'])
            economy.balance_prototype(p, it, self.economy_mode)
            shop[pid] = worlddef.shop_item(p)
            if it.get('upgrade'):  # the plant a full Patch of these becomes: same look, four times the yield
                u = copy.deepcopy(p)
                u.update(id=it['upgrade']['id'], name=it['upgrade']['name'], nameId=it['upgrade']['name'])
                u['graphicalId'] = p.get('graphicalId') or pid
                u['producedReward'] = {k: v * 4 for k, v in p['producedReward'].items()}
                wd[by_id[pid][0]].append(u)
                by_id[u['id']] = (by_id[pid][0], u)
                p['upgradePrototypeId'] = u['id']
        # The shop sells what the original shop showed: story.json items that have a price. Everything else
        # (sand path pieces, seasonal and placeholder graphics, bases sold only as colour variants) stays
        # out; rare plants only grow from seeds. Without story items, every prototype is sold.
        sold = {pid for pid, it in self.data.get('items', {}).items() if it.get('price')}
        rare = {p['id'] for p in wd.get('rarePlantPrototypeList', [])}
        wd['ingameShopItems'] = []
        for pid, s in shop.items():
            if not (pid in sold if sold else pid not in has_variants) or pid in rare:
                continue
            if pid in SEASONAL_ITEMS and not self.in_season(SEASONAL_ITEMS[pid]):
                continue  # holiday decorations are sold during their event
            # Locked below "level": the card shows GET IT EARLY, which costs the price times
            # getItEarlyCostMultiplier plus a gift of algae (DialogGetItEarly, worlddef globalSettings).
            level = int(self.data.get('items', {}).get(pid, {}).get('level', 1))
            # Nursery order (ServerPrototype::getGuiOrder): by unlock level, then by price as in the Let's
            # Play (a pearl counted as 20 sand dollars), so the basic items come first.
            c = s.get('cost') or {}
            order = level * 100000 + min(99999, c.get('virtualMoney', 0) + 20 * c.get('hardMoney', 0))
            by_id[pid][1].update(requiredLevel=level, visibleAtLevel=1, guiOrder=order)
            wd['ingameShopItems'].append(dict(s, requiredLevel=level, visibleAtLevel=1, guiOrder=order))

    def levels(self, wd):
        """Level XP thresholds and level-up rewards (story.json "levels")."""
        lv = self.data.get('levels')
        if not lv:
            return
        xp = list(lv['xp'])
        while len(xp) < len(wd['levelList']):
            xp.append(xp[-1] + (xp[-1] - xp[-2]) + 100)  # gaps keep growing by 100
        for l in wd['levelList']:
            l['requiredXP'] = xp[l['level'] - 1]
            # Level-up gifts the Let's Play showed (story.json "levels.rewards"); other levels give sand dollars and
            # algae growing with the level, and a pearl every fifth level
            r = lv.get('rewards', {}).get(str(l['level'])) or (
                {} if l['level'] == 1 else {'virtualMoney': 50 * l['level'], 'energy': 20 + 5 * l['level'],
                                            'hardMoney': 1 if l['level'] % 5 == 0 else 0})
            r = economy.level_reward(l['level'], r, self.economy_mode)
            l['reward'] = worlddef.reward(xp=0, coins=r.get('virtualMoney', 0), pearls=r.get('hardMoney', 0),
                                          algae=r.get('energy', 0))
            # Vitality caps (Level::LevelDefinition "vitality"): the total and one per category, 1 plants,
            # 2 rare plants, 3 rare fish, 4 guests (DialogUserVitality); past the wiki's table they grow 10 %.
            caps = lv.get('vitality') or []
            if caps:
                c = caps[min(l['level'], len(caps)) - 1]
                if l['level'] > len(caps):
                    c = [int(v * 1.1 ** (l['level'] - len(caps))) for v in c]
                l['vitality'] = {'vitality': c[4], 'categories': [  # the wiki's total, not the categories' sum
                    {'categoryId': i, 'vitality': v} for i, v in enumerate(c[:4], 1)]}

    def name_keys(self, wd):
        """ServerPrototype::getName looks "name" up in the texts bundle, so names become STR_ keys.
        ShopItem::refresh shows a Vitality heart whenever "vitality" is present, so it is dropped at 0."""
        self.names = {}
        for k, v in wd.items():
            if not (k.endswith('PrototypeList') or k == 'patchList') or not isinstance(v, list):
                continue
            for p in v:
                if not isinstance(p, dict) or 'id' not in p:
                    continue
                key = 'STR_PROTO_%s' % p['id'].upper()
                p['name'] = p['nameId'] = NAME_FIXES.get(p['id'], p.get('name'))
                if not str(p.get('name', '')).startswith(('STR_', 'STF_')):
                    text = str(p.get('name') or p['id'])
                    self.names[key] = text[:1].upper() + text[1:]
                    p['name'] = p['nameId'] = key
                if not p.get('vitality'):
                    p.pop('vitality', None)
        for s in wd.get('ingameShopItems', []):
            s.pop('vitality', None)

    def check(self, wd):
        """Every prototype the story refers to must exist, or the client crashes."""
        ids = {p['id'] for k, v in wd.items() if isinstance(v, list) for p in v if isinstance(p, dict) and 'id' in p}
        missing = set()
        for q in self.data['quests']:
            for t in q.get('tasks', []):
                params = t.get('params', [])
                if t['cid'] in PROTOTYPE_TASKS and len(params) > 1 and params[1] and params[1] not in ids:
                    missing.add(str(params[1]))
            for f in [q['giver']] + q.get('grantFish', []) + q.get('rewardPrototypeIdList', []):
                if f not in ids:
                    missing.add(f)
        for d in self.data.get('dialogs', []):
            missing.update(a for l in d['lines'] for a in (l['actor'], l.get('listener')) if a and a not in ids)
        for pid, it in self.data.get('items', {}).items():
            missing.update(r for r in it.get('results', []) if r not in ids)
        for pt in self.data.get('patterns', []):
            missing.update(x for x in [pt['centralPrototype'], pt['producedFishId']] + pt['nearPrototypes'] if x not in ids)
        if missing:
            raise ValueError('story.json refers to unknown prototypes: %s' % ', '.join(sorted(missing)))

    def is_squirt(self, qid):
        """A game of Hide and Seek with Squirt (not Bruce's visit, which is also a minigame quest)."""
        q = self.quests.get(qid, {})
        return q.get('type') == 'SQUIRT_MINIGAME' and any(
            t['cid'] == 'CID_MINIGAME' and t['params'][:1] == ['questGame_Squirt'] for t in q.get('tasks', []))

    def quest_prototype(self, q):
        if self.kids and q.get('kids'):
            k = q['kids']
            q = dict(q, **{f: k[f] for f in ('nameKey', 'descKey', 'rewardKey', 'hintIdList') if f in k})
            if k.get('pattern'):
                q['tasks'] = [dict(t, params=[t['params'][0], k['pattern']]) if t['cid'] == 'CID_PATTERN' else t
                              for t in q['tasks']]
        p = {
            'id': q['id'],
            'type': q.get('type', 'STORY'),
            'autoStart': q.get('autoStart', True),
            'questGiverId': q['giver'],
            'nameStringId': q['nameKey'],
            'descriptionStringId': q['descKey'],
            'reward': reward(q.get('reward')),
            'endConditionList': [
                {'tid': i, 'textId': t['textKey'], 'conditionDefinitionId': t['cid'],
                 'parameterValueList': [{'index': n, 'value': str(v)} for n, v in enumerate(t.get('params', []), 1)]}
                for i, t in enumerate(q.get('tasks', []), 1)],
        }
        if q.get('rewardKey'):  # the text of the "Quest completed" popup (QuestManager::getPrototypeReward)
            p['rewardNameStringId'] = q['rewardKey']
        if p['type'] == 'TIME_EVENT':  # QuestManager::getPrototypeStartEndTimes: CID_TIME_INTERVAL start/end (ms)
            start, end = getattr(self, 'windows', {}).get(q['id'], (0, 0))
            p['startConditionList'] = [{'conditionDefinitionId': 'CID_TIME_INTERVAL', 'parameterValueList': [
                {'index': 1, 'value': start}, {'index': 2, 'value': end}]}]
        if p['type'] == 'HOMEWORK':
            # QuestManager::getPrototypeStartingHourDuration: 1 = start hour, 2 = weekday (1 = Sunday),
            # 3 = minutes it lasts (QuestHomeWork::countTimes); the server opens each day's homework itself
            day = int(q['id'].rsplit('_', 1)[1]) + 1
            p['startConditionList'] = [{'conditionDefinitionId': 'CID_REGULAR_TIME_INTERVAL', 'parameterValueList': [
                {'index': 1, 'value': 0}, {'index': 2, 'value': day}, {'index': 3, 'value': 24 * 60}]}]
        if p['type'] == 'SQUIRT_MINIGAME' and q.get('event'):  # Bruce's weekend visit
            start, end = getattr(self, 'windows', {}).get(q['id'], (0, 0))
            p['startConditionList'] = [{'conditionDefinitionId': 'CID_TIME_INTERVAL', 'parameterValueList': [
                {'index': 1, 'value': start}, {'index': 2, 'value': end}]}]
        elif p['type'] == 'SQUIRT_MINIGAME':
            # QuestManager::getPrototypeStartEndTimes reads the list without a null check; open-ended interval
            p['startConditionList'] = [{'conditionDefinitionId': 'CID_TIME_INTERVAL', 'parameterValueList': [
                {'index': 1, 'value': 1388534400000}, {'index': 2, 'value': 4102444800000}]}]
        for k in ('startDialogId', 'endDialogId', 'hintIdList', 'rewardPrototypeIdList'):
            if q.get(k):
                p[k] = q[k]
        # Android 1.8.1's DialogQuestTimeEvent owns exactly two TaskListRow objects.
        # updateParameters indexes them without checking the task count, so a third
        # objective crashes as soon as the opening conversation finishes. Use the
        # regular quest card for larger events; the source quest and its time
        # interval still drive server scheduling, progress and event rewards.
        if p['type'] == 'TIME_EVENT' and len(p['endConditionList']) > 2:
            p['type'] = 'STORY'
        return p

    # ------------------------------------------------------------ player state
    VERSION = 2  # story.json with the original quest ids (tools/build_story.py)
    MAX_OPEN = 5  # the Let's Play shows up to five quest buttons at a time

    def new_player(self, w):
        w['quests'] = []
        w['finishedTutorialQuests'] = []
        w['messages'] = []
        w['nextQuestId'] = 1
        w['storyVersion'] = self.VERSION
        self.catch_up(w, push=False)

    def migrate(self, w):
        """Reefs saved with older story.json versions: renamed quest ids, quests that no longer exist, and
        the quests before the player's current ones (the order changed) counted as done."""
        changed = 'nextQuestId' not in w
        w.setdefault('nextQuestId', 1)
        w.setdefault('messages', [])
        # the old ids are renamed once: some of them are now the ids of different quests
        renamed = self.renamed if w.get('storyVersion', 1) < self.VERSION else {}
        if w.get('storyVersion') != self.VERSION:
            w['storyVersion'] = self.VERSION
            changed = True
        done = [renamed.get(q, q) for q in w.get('finishedTutorialQuests') or []]
        running = []
        for e in w.get('quests', []):
            pid = renamed.get(e['prototypeId'], e['prototypeId'])
            if pid != e['prototypeId']:
                changed = True
                q = self.quests.get(pid)
                if q and len(e['tasks']) != len(q.get('tasks', [])):
                    e['tasks'] = [{'tid': i, 'progress': {}} for i in range(1, len(q['tasks']) + 1)]
                e['prototypeId'] = pid
            if pid in self.quests and pid not in done:
                running.append(e)
            else:
                changed = True
        reached = set(done) | {e['prototypeId'] for e in running}
        before = set()
        todo = [q for q in reached if q in self.quests]
        while todo:
            for p in self.quests[todo.pop()].get('after', []):
                if p in self.quests and p not in before:
                    before.add(p)
                    todo.append(p)
        new_done = [q for q in dict.fromkeys(done + sorted(before - {e['prototypeId'] for e in running}))
                    if q in self.quests]
        if new_done != w.get('finishedTutorialQuests') or len(running) != len(w.get('quests', [])):
            changed = True
        w['finishedTutorialQuests'] = new_done
        w['quests'] = running
        return changed

    def catch_up(self, w, push=True):
        """Opens the quests the player can have now: level reached and the quests they wait for finished,
        in story order, up to MAX_OPEN at a time. If nothing at all is open (the player is below the next
        quest's level), the next quest opens anyway so the story never stalls. Returns True if anything opened."""
        done = set(w['finishedTutorialQuests'])
        level = int(w.get('status', {}).get('level', 1))
        open_ids = {e['prototypeId'] for e in w['quests']}
        ready = [q for q in self.data['quests']
                 if q['id'] not in done and q['id'] not in open_ids and (w.get('kids') or not q.get('kidsOnly'))
                 and not q.get('homework') and not q.get('event')
                 and all(p in done for p in q.get('after', []))]
        opened = False
        story_open = lambda: sum(1 for e in w['quests'] if not self.quests.get(e['prototypeId'], {}).get('repeat'))
        for q in ready:
            if story_open() >= self.MAX_OPEN and not q.get('repeat'):
                continue
            if q.get('level', 1) <= level:
                self.open(w, q['id'], push)
                opened = True
        ready = [q for q in ready if not q.get('repeat') and q['id'] not in {e['prototypeId'] for e in w['quests']}]
        if not story_open() and ready:
            self.open(w, min(ready, key=lambda q: q.get('level', 1))['id'], push)
            opened = True
        return opened

    def open_homework(self, w, today, weekday, targets):
        """Today's homework (homework_<weekday>, 0 = Sunday): yesterday's goes, today's opens with this player's
        targets [(prototypeId, count)] as task progress (QuestManager::loadTasks reads count, counter and
        prototypeId). Only at startgame, which carries the quest list with its progress."""
        hw = w.get('homework') or {}
        if hw.get('day') == today:
            return
        w['quests'] = [e for e in w['quests'] if not self.quests.get(e['prototypeId'], {}).get('homework')]
        qid = 'homework_%d' % weekday
        q = self.quests.get(qid)
        # Homework comes with its tutorial ("tap the homework button" needs the button, which a HOMEWORK quest
        # shows), whichever way the tutorial opened (catch_up may open it before its "after" quests are done)
        tutorial = any(e['prototypeId'] == 'homework_tutorial_01' for e in w['quests']) \
            or 'homework_tutorial_01' in w['finishedTutorialQuests']
        if not q or not (tutorial or (all(p in w['finishedTutorialQuests'] for p in q.get('after', []))
                                      and int(w['status'].get('level', 1)) >= q.get('level', 1))):
            return
        sid = w['nextQuestId']
        w['nextQuestId'] += 1
        tasks = []
        for i, (pid, count) in enumerate(targets, 1):
            tasks.append({'tid': i, 'progress': {'count': count, 'counter': count, 'prototypeId': pid, 'state': 1}})
        w['quests'].append({'prototypeId': qid, 'id': sid, 'state': RUNNING, 'tasks': tasks})
        w['homework'] = {'day': today, 'id': sid}

    def open(self, w, qid, push=True):
        q = self.quests.get(qid)
        if not q or qid in w['finishedTutorialQuests'] or any(e['prototypeId'] == qid for e in w['quests']):
            return
        sid = w['nextQuestId']
        w['nextQuestId'] += 1
        entry = {'prototypeId': qid, 'id': sid, 'state': RUNNING if q.get('autoStart', True) else OFFERED,
                 'tasks': [{'tid': i, 'progress': {}} for i in range(1, len(q.get('tasks', [])) + 1)]}
        w['quests'].append(entry)
        if push:
            w['messages'].append({'id': self.message_id(w), 'type': QUEST_OPEN,
                                  'data': {'prototypeId': qid, 'id': sid, 'tasks': []}})

    @staticmethod
    def message_id(w):
        n = w.get('nextMessageId', 1)
        w['nextMessageId'] = n + 1
        return n

    def find(self, w, sid):
        return next((e for e in w['quests'] if e['id'] == sid), None)

    def start(self, w, d):
        e = self.find(w, d.get('id'))
        if e:
            e['state'] = RUNNING

    def recover_seed_tasks(self, w, protos, finish):
        """Recover missed seed progress from saved provenance when loading a reef.

        A seed becomes a plant with a different prototypeId. Its seedPrototypeId
        is the evidence for seed tasks; an ordinary nursery plant is not enough.
        Use a lower bound from current entities, never increment a counter on
        each login or reduce progress for a plant the player has since sold.
        Complete through task_state so rewards and unlocks occur exactly once.
        """
        mature = (1, 6, 7)  # BUILT, PRODUCING, READY (actions imports worlddef too)
        entities = [e for name in ('corals', 'livingPlants', 'ornamentalPlants', 'rarePlants')
                    for e in w.get(name, []) if e.get('seedPrototypeId')]
        for entry in list(w.get('quests', [])):
            if entry.get('state') != RUNNING:
                continue
            q = self.quests.get(entry['prototypeId'], {})
            changed = False
            last_tid = None
            for tid, task in enumerate(q.get('tasks', []), 1):
                params = task.get('params', [])
                cid = task['cid']
                categories = None
                if cid in ('CID_CREATED', 'CID_GROWN') and len(params) >= 2 and str(params[1]).startswith('seed_'):
                    count, seed = int(params[0]), params[1]
                    grown = cid == 'CID_GROWN'
                elif cid == 'CID_GROW_ANY' and len(params) >= 3 and str(params[2]).startswith('seed_'):
                    categories = set(str(params[0]).split(','))
                    count, seed = int(params[1]), params[2]
                    grown = True
                else:
                    continue
                saved = next((s for s in entry['tasks'] if s['tid'] == tid), None)
                if saved is None or saved.get('finished'):
                    continue
                matches = set()
                for entity in entities:
                    if entity.get('seedPrototypeId') != seed or (grown and entity.get('state') not in mature):
                        continue
                    _, p = protos.get(entity.get('prototypeId'))
                    if not p or (categories and p.get('shopCategory') not in categories):
                        continue
                    _, seed_p = protos.get(seed)
                    if grown and entity.get('growingCycle', 0) < (seed_p or {}).get('growingCycles', 1):
                        continue
                    matches.add(entity['id'])
                if not matches:
                    continue
                progress = saved.setdefault('progress', {})
                remaining = max(0, count - len(matches))
                remaining = min(int(progress.get('counter', count)), remaining)
                progress.update(count=count, counter=remaining, state=1)
                if cid != 'CID_GROW_ANY':
                    progress['prototypeId'] = seed
                else:
                    progress.pop('prototypeId', None)
                if remaining == 0:
                    saved['finished'] = True
                changed = True
                last_tid = tid
            if changed and all(s.get('finished') for s in entry['tasks']):
                self.task_state(w, {'id': entry['id'], 'tid': last_tid, 'finished': True}, finish)

    def task_state(self, w, d, finish):
        """questTaskSetState: returns {"questFinished": bool}."""
        e = self.find(w, d.get('id'))
        if not e:
            return {'questFinished': False}
        tid = d.get('tid')
        task = next((t for t in e['tasks'] if t['tid'] == tid), None)
        if task is None:
            task = {'tid': tid, 'progress': {}}
            e['tasks'].append(task)
        prog = {k: v for k, v in (d.get('progress') or {}).items() if v not in (None, '')}
        if prog.get('state') == 2:
            prog['state'] = 1  # finished tasks are marked with "finished" instead
        task['progress'].update(prog)
        if d.get('finished'):
            task['finished'] = True
            task['progress']['counter'] = 0
        q = self.quests.get(e['prototypeId'], {})
        done = len(e['tasks']) >= len(q.get('tasks', [])) and all(t.get('finished') for t in e['tasks'])
        if done:
            # Story rewards with new pearl bonuses use the current catalogue.
            # Keep the separate minigame/event reward protocol unchanged.
            r = (q.get('reward') if self.economy_mode == 'revival' and q.get('type') == 'STORY'
                 else d.get('reward') or q.get('reward'))
            finish(q, r)
            w['quests'].remove(e)
            if q.get('repeat'):  # Hide and Seek: always there again, catch_up reopens it
                pass
            elif q.get('homework'):  # done for today; tomorrow brings the next one
                w.setdefault('homework', {})['done'] = True
            elif q.get('event'):  # done for this time; the event comes back next season / rotation
                windows = getattr(self, 'windows', None) or self.event_windows(int(time.time() * 1000))
                w.setdefault('eventsDone', {})[q['id']] = windows[q['id']][0]
                self.run_events(w, int(time.time() * 1000))
            elif e['prototypeId'] not in w['finishedTutorialQuests']:
                w['finishedTutorialQuests'].append(e['prototypeId'])
            self.catch_up(w)
        return {'questFinished': done}

    def buy_hint(self, w, d, pay):
        e = self.find(w, d.get('id'))
        if not e:
            return
        q = self.quests.get(e['prototypeId'], {})
        idx = int(d.get('hintIndex', 0))
        hint = next((h for h in self.data.get('hints', [])
                     if h['id'] in q.get('hintIdList', []) and h.get('index', 0) == idx), None)
        if hint:
            pay(hint.get('cost'))
        e['hintPurchasedIndex'] = max(idx, e.get('hintPurchasedIndex', -1))

    def confirm(self, w, d):
        ids = set(d.get('ids') or [])
        w['messages'] = [m for m in w.get('messages', []) if m['id'] not in ids]


